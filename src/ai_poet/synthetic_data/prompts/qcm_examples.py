"""Few-shot QCM examples used to teach varied, poem-grounded questions."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class QcmFewShot:
    meter_name: str
    couplet_count: int
    poem: str
    qcm: dict[str, object]


# A metered example with a question about the main idea and a reasoning that
# demonstrates the full conceptual path.
METERED_QCM_FEW_SHOT = QcmFewShot(
    meter_name="الخفيف",
    couplet_count=3,
    poem=(
        "كَيْفَ تَرْقَى رُقِيَّكَ الأَنْبِيَاءُ = يَا سَمَاءً مَا طَاوَلَتْهَا سَمَاءُ\n"
        "لَمْ يُسَاوُوكَ فِي عُلاَكَ وَقَدْ حَا = لَ سَنىً مِنْكَ دُونَهُمْ وَسَنَاءُ\n"
        "إِنَّمَا مَثَّلُوا صِفَاتِكَ لِلنَّا = سِ كَمَا مَثَّلَ النُّجُومَ الْمَاءُ"
    ),
    qcm={
        "question": "ما الفكرة الأساسية التي تبرزها الأبيات في وصف الممدوح؟",
        "choices": {
            "ا": "بيان أن الممدوح يعلو على الأنبياء في كل صفاتهم.",
            "ب": "إثبات أن منزلة الممدوح أرفع من أن تدركها المقامات العليا، وأن ما يظهر منها إنما هو انعكاس ناقص.",
            "ج": "وصف فضائل الممدوح الصريحة كما يرويها عنه الناس.",
            "د": "الشكوى من صعوبة بلوغ منزلة الممدوح العالية.",
        },
        "reasoning": (
            "السؤال يطلب الفكرة الأساسية في وصف الممدوح، فأنظر إلى البيت الأول: "
            "«كيف ترقى رقيك الأنبياء» يقرر أن حتى الأنبياء لا يبلغون رقيه، وهذا "
            "يؤكد علوًا يتعذر إدراكه. ولا أقف عند هذا، بل أتابع البيت الثالث "
            "«إنما مثلوا صفاتك للناس كما مثل النجوم الماء»، فهو يبين أن الذي "
            "يظهر للناس من صفاته ليس حقيقتها الكاملة، بل انعكاس يشبه النجوم في "
            "الماء. بجمع البيتين أجد أن الفكرة ليست مجرد تفوق بالصفات كما في ا، "
            "ولا وصفًا للفضائل كما في ج، ولا شكوى كما في د، بل هي أن منزلته "
            "أسمى من أن تدرك، وأن ما يظهر منها انعكاس ناقص. لهذا يكون الخيار ب "
            "هو الأدق لأنه يجمع عنصرَي التعذر والانعكاس معًا."
        ),
        "correct_answer": "ب",
    },
)


# A metered example with a question about a contrast and a reasoning that
# compares the choices in detail.
METERED_CONTRAST_QCM_FEW_SHOT = QcmFewShot(
    meter_name="الرمل",
    couplet_count=4,
    poem=(
        "أَيُّها الفاسي أَتى ريحُكَ قبلَ النجو يَفغَم = في قَريض حَسَن الصورةِ بالهَجو مُجذَّم\n"
        "لا تَراهُ الدهرَ إِلّا بِغَريمِ الكَأسِ مُغرَم = يَرفُضُ النفلَ مَعَ الفَرضِ أَوانَ الزيرِ وَالبَم"
    ),
    qcm={
        "question": "ما التناقض الذي يبرزه الشاعر في وصف المخاطَب؟",
        "choices": {
            "ا": "بين جمال صورة القريض وقبح معناه في الهجاء.",
            "ب": "بين ادعاء العلم والفقه وبين الانشغال باللهو والشراب ورفض العبادات.",
            "ج": "بين وصول رسائله قبل النجوى وبين تأخرها في الوصول.",
            "د": "بين كونه غريم الكأس وبين كونه فقيهًا يحفظ المتون.",
        },
        "reasoning": (
            "السؤال يخص التناقض في وصف المخاطَب، فأركز على الأبيات التي تصف "
            "شخصيته. أجد في البيت الثالث وصفه بأنه «غريم الكأس مغرم» أي ملازم "
            "للشراب، وفي البيت الرابع أنه «يرفض النفل مع الفرض» أي يترك العبادات "
            "المفروضة والمستحبة. حين أجمع هذين المعنيين مع وصفه بأنه «فقيه عالم» "
            "كما يُفهَم من السياق، يظهر تناقض صارخ بين هيئة العلم التي يظهر بها "
            "وبين سلوكه الفعلي المنهمك في اللهو. الخيار ا يذكر تناقضًا في القريض "
            "لا في الشخصية، والـ ج يتعلق بوصول الرسائل وليس بالشخص، والـ د يقرّب "
            "المعنى لكنه يجعله غريم كأس فقط دون ذكر رفض العبادات وادعاء العلم. "
            "الخيار ب هو الأجمع لأنه يضم طرفَي التناقض: ادعاء العلم والفقه من "
            "جهة، والانشغال بالملذات ورفض العبادات من جهة أخرى."
        ),
        "correct_answer": "ب",
    },
)


# A prose example with a question about an image and a reasoning tied to the
# specific wording.
PROSE_QCM_FEW_SHOT = QcmFewShot(
    meter_name="النثر",
    couplet_count=2,
    poem=(
        "يجيء المساء وفي كفّه بقايا الضوء = فأجمع من صمته نافذةً للرجاء\n"
        "يمرّ الغياب على القلب ثقيلًا = لكنّ ذكرى الأحبة تعلّمه أن يضيء"
    ),
    qcm={
        "question": "ما دلالة صورة «نافذةً للرجاء» في هذه المقطوعة؟",
        "choices": {
            "ا": "أن الرجاء يلغي العتمة تمامًا ويملأ القلب نورًا.",
            "ب": "أن الرجاء يظهر من العتمة بوصفه منفذًا محدودًا لا يزيل الحزن كله.",
            "ج": "أن النافذة مكان حقيقي يخرج منه الشاعر إلى الخارج.",
            "د": "أن الرجاء يتحول إلى شيء مادي يفتحه الشاعر بقوة.",
        },
        "reasoning": (
            "السؤال يسأل عن دلالة صورة «نافذة للرجاء»، فأعود إلى السياق: المساء "
            "يحمل «بقايا الضوء»، أي أن النور أفلّ ولم يبق منه إلا شيء قليل. ومن "
            "«صمته» يجمع الشاعر نافذة للرجاء. كلمة «نافذة» توحي بفتحة تسمح "
            "بمرور الضوء من غير أن تلغي الجدار أو العتمة، وهذا ينسجم مع أن "
            "الرجاء هنا ليس إزالة كاملة للحزن بل منفذ محدود يسمح بالأمل. الخيار "
            "ا يقول إن الرجاء يلغي العتمة تمامًا، وهذا يخالف طبيعة النافذة "
            "والسياق. والـ ج يحمّل الصورة معنى حرفيًا مكانيًا لا يثبته النص. "
            "والـ د يجعل الرجاء شيئًا ماديًا يُفتح بقوة، وهذه إضافة غير موجودة. "
            "الخيار ب هو الأدق لأنه يلتقط جوهر الاستعارة: رجاء ينبع من العتمة "
            "بوصفه منفذًا محدودًا لا يمحو الحزن."
        ),
        "correct_answer": "ب",
    },
)


