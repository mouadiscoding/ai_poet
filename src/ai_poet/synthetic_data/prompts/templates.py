def meter_explanation(meter_name: str) -> str:
    """Render the trusted prosody reference injected into every prompt."""
    try:
        details = METER_DEFINITIONS[meter_name]
    except KeyError as exc:
        raise ValueError(f"Unknown meter name: {meter_name}") from exc
    return (
        "شرح البحر {meter_name}:\n"
        f"{details['definition']}\n"
        "وزنه في كل بيت كامل:\n"
        f"{details['full_verse_pattern']}\n\n"
        "الصورة الصوتية التقريبية:\n"
        f"{details['sound_pattern']}\n"
        "حيث ـ مقطع طويل، وب مقطع قصير. الوزن يُفحص بحسب النطق لا الرسم؛ "
        "تسقط همزة الوصل في الوصل، ويُنطق التنوين نونًا ساكنة، وتُفك الشدة "
        "إلى حرفين، وقد تعبر التفعيلة حدود الكلمات. تقبل الزحافات والعلل "
        "الموروثة الصحيحة ولا تُفرض الصورة الأصلية بصورة جامدة."
    )


def plan_heading(meter_name: str) -> str:
    """Return the required final instruction heading for verse or prose."""
    if meter_name == "النثر":
        return "خطة عملية لصناعة نص شعري منثور:"
    return f"خطة عملية لصناعة بيت على بحر {meter_name}:"


